export function getLanguage(code: string): LanguageConfig {
  const lang = SUPPORTED_LANGUAGES.find(
    l => l.code === code || l.code.toLowerCase() === code.toLowerCase() || l.code.startsWith(code)
  );
  return lang || SUPPORTED_LANGUAGES[0];
}
